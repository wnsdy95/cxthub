// ClaudeCodec is an implementation of ProviderCodec for converting Claude Code JSONL ↔ CIR (provider compatibility rules).
//
// Decode mapping (block-to-block 1:1 → CIR event):
//   - assistant block thinking{thinking,signature} → reasoning(locked{scheme:signature,blob:signature}, redacted_summary=thinking, cross_replayable:false)
//   - assistant block text{text}                    → message(role:assistant, blocks:[{text}])
//   - assistant block tool_use{id,name,input}       → tool_call(call_id:id, provider_tool_name:name, tool_name:canonical(name), input)
//   - user block tool_result{tool_use_id,content}   → tool_result(call_id:tool_use_id, output:content)
//   - user content(string|text block)               → message(role:user, blocks:[{text}])
//   - envelope: cwd/gitBranch/sessionId/version/timestamp are embedded fields in the record, model is message.model
//   - records without queue-operation / message are dropped
//
// Encode(target=claude): full — thinking{signature} original text reinsertion (FidelityFull).
// Encode(target!=claude): reconstructed — locked inactive (redacted_summary only as text), tool_name remapping.
//
// Encoding emits 1 record per event (no block grouping). Normal Claude-native events round-trip meaning-equivalently.
// Tool_result outputs not matching the target schema are normalized to string for API safety, so structural equality for arbitrary polluted CIR is not guaranteed.
type ClaudeCodec struct{}

// NewClaudeCodec creates a new ClaudeCodec.
func NewClaudeCodec() *ClaudeCodec { return &ClaudeCodec{} }

// Provider returns the provider (claude) this codec is responsible for.
func (c *ClaudeCodec) Provider() domain.ProviderKind { return domain.ProviderClaude }

// claudeRecord is the structure of a Claude session JSONL line (as we use it).
type claudeRecord struct {
	Type      string         `json:"type"`
	Subtype   string         `json:"subtype,omitempty"`
	Message   *claudeMessage `json:"message,omitempty"`
	Cwd       string         `json:"cwd,omitempty"`
	SessionID string         `json:"sessionId,omitempty"`
	GitBranch string         `json:"gitBranch,omitempty"`
	Version   string         `json:"version,omitempty"`
	Timestamp string         `json:"timestamp,omitempty"`
	// IsCompactSummary — This user record is a summary generated by the agent's context compression (empirically:
	// displayed in the user message right after compact_boundary). Agent-generated memorized data.
	IsCompactSummary bool `json:"isCompactSummary,omitempty"`
}

type claudeMessage struct {
	Role    string          `json:"role"`
	Model   string          `json:"model,omitempty"`
	Content json.RawMessage `json:"content"`
	Usage   *claudeUsage    `json:"usage,omitempty"`
}

// claudeUsage is the token usage in the assistant message (Claude Code JSONL message.usage).
type claudeUsage struct {
	InputTokens              int `json:"input_tokens"`
	CacheCreationInputTokens int `json:"cache_creation_input_tokens"`
	CacheReadInputTokens     int `json:"cache_read_input_tokens"`
	OutputTokens             int `json:"output_tokens"`
}

type claudeBlock struct {
	Type      string                 `json:"type"`
	Text      string                 `json:"text,omitempty"`
	Thinking  string                 `json:"thinking,omitempty"`
	Signature string                 `json:"signature,omitempty"`
	ID        string                 `json:"id,omitempty"`
	Name      string                 `json:"name,omitempty"`
	Input     map[string]interface{} `json:"input,omitempty"`
	ToolUseID string                 `json:"tool_use_id,omitempty"`
	Content   json.RawMessage        `json:"content,omitempty"`
}

// Decode converts Claude JSONL bytes to a CIRDocument.
func (c *ClaudeCodec) Decode(_ context.Context, raw []byte) (domain.CIRDocument, error) {
	doc := domain.CIRDocument{}
	doc.Envelope.CIRVersion = domain.CIRVersionV1
	doc.Envelope.SourceProvider = domain.ProviderClaude
	doc.Envelope.Fidelity = domain.FidelityFull

	var events []domain.Event
	sc := bufio.NewScanner(bytes.NewReader(raw))
	sc.Buffer(make([]byte, 0, 1024*1024), 64*1024*1024)
	for sc.Scan() {
		line := bytes.TrimSpace(sc.Bytes())
		if len(line) == 0 {
			continue
		}
		var rec claudeRecord
		if err := json.Unmarshal(line, &rec); err != nil {
			return domain.CIRDocument{}, fmt.Errorf("claude decode: %w", err)
		}
		setIfEmpty(&doc.Envelope.Cwd, rec.Cwd)
		setIfEmpty(&doc.Envelope.GitBranch, rec.GitBranch)
		setIfEmpty(&doc.Envelope.SessionOriginID, rec.SessionID)
		setIfEmpty(&doc.Envelope.CapturedAt, rec.Timestamp)
		// Context compression boundary: Claude is compressed when type=="system"&&subtype=="compact_boundary"
		// Marker is left inline (without message). sessionId remains unchanged so it's not picked up as a session boundary
		// Sent separately — the only signal graph draws the compression marker (◈).
		if rec.Type == "system" && rec.Subtype == "compact_boundary" {
			doc.Envelope.CompactionCount++
			// Preserve the boundary in the archival stream. Claude writes the
			// replacement summary as the following isCompactSummary message, so
			// the effective context is the suffix after this explicit empty
			// replacement boundary.
			events = append(events, domain.Event{
				Kind: domain.EventCompaction, Ts: rec.Timestamp,
				Replacement:         []domain.Event{},
				ReplacementComplete: true,
			})
		}
		if rec.Message == nil {
			continue // queue-operation, summary/compact_boundary (no message) etc. drop
		}
		noteModel(&doc.Envelope, rec.Message.Model)
		if u := rec.Message.Usage; u != nil {
			doc.Envelope.OutputTokens += u.OutputTokens
			// Context window size = sum of input at this point (new + cache creation + cache read).
			// Last observed value is soon the context size at session end.
			if ctx := u.InputTokens + u.CacheCreationInputTokens + u.CacheReadInputTokens; ctx > 0 {
				doc.Envelope.ContextTokens = ctx
			}
		}
		role := rec.Message.Role
		if role == "" {
			role = "assistant"
		}
		blocks, err := parseClaudeContent(rec.Message.Content)
		if err != nil {
			return domain.CIRDocument{}, fmt.Errorf("claude decode content: %w", err)
		}
		for _, b := range blocks {
			ev := domain.Event{Ts: rec.Timestamp}
			switch b.Type {
			case "text", "":
				ev.Kind = domain.EventMessage
				ev.Role = role
				ev.Blocks = []domain.ContentBlock{{Type: "text", Text: b.Text}}
				ev.CompactSummary = rec.IsCompactSummary
			case "thinking":
				ev.Kind = domain.EventReasoning
				ev.Locked = &domain.LockedBlob{Provider: domain.ProviderClaude, Scheme: "signature", Blob: b.Signature}
				ev.RedactedSummary = b.Thinking
				ev.CrossReplayable = false
			case "tool_use":
				ev.Kind = domain.EventToolCall
				ev.CallID = b.ID
				ev.ProviderToolName = b.Name
				ev.ToolName = canonicalToolName(b.Name)
				ev.Input = b.Input
			case "tool_result":
				ev.Kind = domain.EventToolResult
				ev.CallID = b.ToolUseID
				ev.Output = normalizeToolResultOutput(decodeJSONValue(b.Content))
			default:
				// Unknown block: preserved as text (to prevent loss)
				ev.Kind = domain.EventMessage
				ev.Role = role
				ev.Blocks = []domain.ContentBlock{{Type: "text", Text: b.Text}}
			}
			events = append(events, ev)
		}
	}
	if err := sc.Err(); err != nil {
		return domain.CIRDocument{}, fmt.Errorf("claude decode scan: %w", err)
	}
	doc.Events = assignSeq(events)
	doc.Envelope.CIRVersion = domain.CIRVersionForEvents(doc.Events)
	return doc, nil
}

// Encode converts CIRDocument to target provider JSONL bytes.
func (c *ClaudeCodec) Encode(_ context.Context, doc domain.CIRDocument, _ domain.ProviderKind) ([]byte, error) {
	// Output format is this codec's provider (claude). full (reinject original) only if CIR source is claude.
	// If source is codex, reconstructed (claude signature not present so locked inactive).
	full := doc.Envelope.SourceProvider == domain.ProviderClaude
	var records []claudeRecord
	emit := func(rec claudeRecord) error { records = append(records, rec); return nil }
	model := doc.Envelope.SourceModel

	for _, ev := range normalizeCIR(doc).Events {
		base := claudeRecord{
			Cwd:       doc.Envelope.Cwd,
			GitBranch: doc.Envelope.GitBranch,
			SessionID: doc.Envelope.SessionOriginID,
			Timestamp: ev.Ts,
		}
		switch ev.Kind {
		case domain.EventMessage:
			base.Type = recordTypeForRole(ev.Role)
			base.IsCompactSummary = ev.CompactSummary // round trip preservation of compact summary flag
			msg := &claudeMessage{Role: ev.Role, Content: marshalClaudeTextBlocks(ev.Blocks)}
			if ev.Role == "assistant" {
				msg.Model = model
			}
			base.Message = msg
		case domain.EventToolCall:
			name := ev.ProviderToolName
			if !full || name == "" {
				name = providerToolName(domain.ProviderClaude, ev.ToolName)
			}
			base.Type = "assistant"
			base.Message = &claudeMessage{Role: "assistant", Model: model, Content: marshalClaudeBlocks([]claudeBlock{{
				Type: "tool_use", ID: ev.CallID, Name: name, Input: nonNilMap(ev.Input),
			}})}
		case domain.EventToolResult:
			base.Type = "user"
			// Claude tool_result.content allows only string or unique Claude content block
			// Native image/document etc. preserved in full round trip, Codex input_text/output_text arrays forced to plain text to prevent resume 400.
			out, _ := json.Marshal(claudeToolResultContent(ev.Output, full))
			base.Message = &claudeMessage{Role: "user", Content: marshalClaudeBlocks([]claudeBlock{{
				Type: "tool_result", ToolUseID: ev.CallID, Content: out,
			}})}
		case domain.EventReasoning:
			if full && ev.Locked != nil && ev.Locked.Scheme == "signature" {
				base.Type = "assistant"
				base.Message = &claudeMessage{Role: "assistant", Model: model, Content: marshalClaudeBlocks([]claudeBlock{{
					Type: "thinking", Thinking: ev.RedactedSummary, Signature: ev.Locked.Blob,
				}})}
			} else {
				// reconstructed: locked inactive, plain summary text only forced. Omit if no summary.
				if ev.RedactedSummary == "" {
					continue
				}
				base.Type = "assistant"
				base.Message = &claudeMessage{Role: "assistant", Model: model, Content: marshalClaudeTextBlocks([]domain.ContentBlock{{Type: "text", Text: ev.RedactedSummary}})}
			}
		case domain.EventCompaction:
			if ev.Replacement == nil || !ev.ReplacementComplete {
				continue // provider-locked Codex active state is never cross-injected
			}
			base.Type = "system"
			base.Subtype = "compact_boundary"
		default:
			continue // turn is not represented in Claude records
		}
		if err := emit(base); err != nil {
			return nil, fmt.Errorf("claude encode: %w", err)
		}
	}
	// token statistics reattachment: attach aggregate value (envelope) to the last assistant message's usage
	// decode→encode→decode round trip is made lossless (last observation = context size,
	// single usage record = output sum).
	if doc.Envelope.ContextTokens > 0 || doc.Envelope.OutputTokens > 0 {
		for i := len(records) - 1; i >= 0; i-- {
			if m := records[i].Message; m != nil && m.Role == "assistant" {
				m.Usage = &claudeUsage{InputTokens: doc.Envelope.ContextTokens, OutputTokens: doc.Envelope.OutputTokens}
				break
			}
		}
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf) // Encode adds '\n' per line → JSONL
	enc.SetEscapeHTML(false)
	for _, rec := range records {
		if err := enc.Encode(rec); err != nil {
			return nil, fmt.Errorf("claude encode: %w", err)
		}
	}
	return buf.Bytes(), nil
}

// --- Helper ---

func setIfEmpty(dst *string, v string) {
	if *dst == "" && v != "" {
		*dst = v
	}
}

func containsStr(list []string, s string) bool {
	for _, x := range list {
		if x == s {
			return true
		}
	}
	return false
}

// noteModel records observed models in the session to the envelope (shared semantics of two codecs):
// SourceModel is last-wins (last used model is the representative value), SourceModels is cumulative by appearance (no duplicates).
// "<synthetic>" is a placeholder for records synthesized by Claude Code (error notices, etc.) — it is not a real model — do not include in representative or cumulative.
func noteModel(env *domain.Envelope, m string) {
	if m == "" || m == "<synthetic>" {
		return
	}
	env.SourceModel = m
	if !containsStr(env.SourceModels, m) {
		env.SourceModels = append(env.SourceModels, m)
	}
}

func recordTypeForRole(role string) string {
	if role == "user" {
		return "user"
	}
	return "assistant"
}

func nonNilMap(m map[string]interface{}) map[string]interface{} {
	if m == nil {
		return map[string]interface{}{}
	}
	return m
}

// parseClaudeContent normalizes message.content (string or block array) to a claudeBlock slice.
func parseClaudeContent(raw json.RawMessage) ([]claudeBlock, error) {
	if len(raw) == 0 {
		return nil, nil
	}
	var s string
	if err := json.Unmarshal(raw, &s); err == nil {
		return []claudeBlock{{Type: "text", Text: s}}, nil
	}
	var blocks []claudeBlock
	if err := json.Unmarshal(raw, &blocks); err != nil {
		return nil, err
	}
	return blocks, nil
}

func marshalClaudeBlocks(blocks []claudeBlock) json.RawMessage {
	b, _ := json.Marshal(blocks)
	return b
}

func marshalClaudeTextBlocks(blocks []domain.ContentBlock) json.RawMessage {
	out := make([]claudeBlock, 0, len(blocks))
	for _, b := range blocks {
		out = append(out, claudeBlock{Type: "text", Text: b.Text})
	}
	return marshalClaudeBlocks(out)
}

// Ensure ClaudeCodec implements outbound.ProviderCodec.
var _ outbound.ProviderCodec = (*ClaudeCodec)(nil)
