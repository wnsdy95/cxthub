CREATE TABLE graph_qualification (
    repo_id text PRIMARY KEY REFERENCES graph_projection_work(repo_id) ON DELETE CASCADE,
    enabled boolean NOT NULL DEFAULT false,
    fence bigint NOT NULL DEFAULT 0 CHECK (fence >= 0),
    lease_until timestamptz,
    next_attempt timestamptz NOT NULL DEFAULT clock_timestamp(),
    reason text NOT NULL DEFAULT '' CHECK (reason IN ('','not_current','read_error','resource_limit')),
    attempt_dataset uuid,
    attempt_epoch uuid,
    attempt_seq bigint CHECK (attempt_seq >= 0),
    attempt_rules integer CHECK (attempt_rules > 0),
    attempt_comparison_rules integer CHECK (attempt_comparison_rules > 0),
    attempt_work_dataset uuid,
    result_dataset uuid,
    result_epoch uuid,
    result_seq bigint CHECK (result_seq >= 0),
    result_rules integer CHECK (result_rules > 0),
    result_comparison_rules integer CHECK (result_comparison_rules > 0),
    expected_hash text CHECK (expected_hash ~ '^sha256:[0-9a-f]{64}$'),
    actual_hash text CHECK (actual_hash ~ '^sha256:[0-9a-f]{64}$'),
    result_state text CHECK (result_state IN ('matched','mismatch')),
    completed_at timestamptz,
    CHECK (num_nonnulls(attempt_dataset,attempt_epoch,attempt_seq,attempt_rules,attempt_comparison_rules,attempt_work_dataset) IN (0,6)),
    CHECK (lease_until IS NULL OR (enabled AND fence > 0 AND attempt_dataset IS NOT NULL)),
    CHECK (num_nonnulls(result_dataset,result_epoch,result_seq,result_rules,result_comparison_rules,
        expected_hash,actual_hash,result_state,completed_at) IN (0,9)),
    CHECK ((result_state='matched') = (expected_hash=actual_hash))
);
